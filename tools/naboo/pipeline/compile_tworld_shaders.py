"""Compile the cooked-world shaders to SPIR-V and write them as C arrays.
  py compile_tworld_shaders.py
Input : naboo_src/codemp/rd-vulkan/shaders/glsl/tworld/tworld.{vert,frag}
Output: naboo_src/codemp/rd-vulkan/shaders/spirv/tworld_data.c
Uses the glslangValidator that ships with RenderDoc (no Vulkan SDK is installed on this machine); set
GLSLANG to use another one. The renderer's own compile.bat is not involved: these shaders live in a
sub-folder it does not scan."""
import os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
RD = os.path.normpath(os.path.join(HERE, "..", "..", "naboo_src", "codemp", "rd-vulkan", "shaders"))
GLSLANG = os.environ.get("GLSLANG", r"E:\RenderDoc\plugins\spirv\glslangValidator.exe")
out = ["// generated by naboo/tools/compile_tworld_shaders.py from shaders/glsl/tworld/ - do not edit\n"]
for stage in ("vert", "frag"):
    src = os.path.join(RD, "glsl", "tworld", "tworld." + stage)
    spv = os.path.join(tempfile.gettempdir(), "tworld_%s.spv" % stage)
    r = subprocess.run([GLSLANG, "-S", stage, "-V", "-o", spv, src], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout, r.stderr); sys.exit(1)
    data = open(spv, "rb").read(); os.remove(spv)
    assert len(data) % 4 == 0
    out.append("const unsigned char tworld_%s_spv[%d] = {\n" % (stage, len(data)))
    for i in range(0, len(data), 16):
        out.append("\t" + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",\n")
    out.append("};\n")
    print("tworld.%s -> %d bytes" % (stage, len(data)))
dst = os.path.join(RD, "spirv", "tworld_data.c")
open(dst, "w", newline="\n").write("".join(out))
print("wrote", dst)
